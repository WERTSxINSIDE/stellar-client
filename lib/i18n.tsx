const dictionaries: Record<Lang, Dictionary> = { ru, en };

type I18nContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  chooseLang: (lang: Lang) => void;
  showGate: boolean;
  t: (key: string, vars?: Vars) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

const STORAGE_KEY = "stellar_lang";
const COOKIE_KEY = "stellar_lang";

function detectLang(): Lang {
  if (typeof navigator === "undefined") return "ru";
  const browser = (navigator.language || "").toLowerCase();
  return browser.startsWith("ru") ? "ru" : "en";
}

function translate(lang: Lang, key: string, vars?: Vars): string {
  let value = dictionaries[lang][key] ?? dictionaries.ru[key] ?? key;
  if (vars) {
    value = value.replace(/\{(\w+)\}/g, (_, name: string) =>
      String(vars[name] ?? "")
    );
  }
  return value;
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ru");
  const [showGate, setShowGate] = useState(false);

  useEffect(() => {
    let stored: string | null = null;
    try {
      stored = window.localStorage.getItem(STORAGE_KEY);
    } catch {
      // localStorage может быть недоступен
    }

    const initial = stored === "ru" || stored === "en" ? (stored as Lang) : detectLang();
    setLangState(initial);
    document.documentElement.lang = initial;

    if (!stored) setShowGate(true);
  }, []);

  const persist = useCallback((next: Lang) => {
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // не критично
    }
    document.cookie = `${COOKIE_KEY}=${next}; path=/; max-age=31536000; samesite=lax`;
    document.documentElement.lang = next;
  }, []);

  const setLang = useCallback(
    (next: Lang) => {
      setLangState(next);
      persist(next);
    },
    [persist]
  );

  const chooseLang = useCallback(
    (next: Lang) => {
      setLangState(next);
      persist(next);
      setShowGate(false);
    },
    [persist]
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      lang,
      setLang,
      chooseLang,
      showGate,
      t: (key: string, vars?: Vars) => translate(lang, key, vars),
    }),
    [lang, setLang, chooseLang, showGate]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    return {
      lang: "ru",
      setLang: () => {},
      chooseLang: () => {},
      showGate: false,
      t: (key: string, vars?: Vars) => translate("ru", key, vars),
    };
  }
  return ctx;
}
