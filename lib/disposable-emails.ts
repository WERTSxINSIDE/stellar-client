/** Достаёт домен из адреса: "User@Sub.Mailinator.com" -> "sub.mailinator.com". */
export function emailDomain(email: string): string {
  const at = String(email || "").lastIndexOf("@");
  if (at === -1) return "";
  return email
    .slice(at + 1)
    .trim()
    .toLowerCase()
    .replace(/\.+$/, "");
}

/** Включена ли проверка (по умолчанию — да). */
export function disposableEmailBlockEnabled(): boolean {
  return String(process.env.DISPOSABLE_EMAIL_BLOCK ?? "1").trim() !== "0";
}

/** true, если домен в списке одноразовых (включая поддомены). */
export function isDisposableEmail(email: string): boolean {
  if (!disposableEmailBlockEnabled()) return false;

  const domain = emailDomain(email);
  if (!domain) return false;

  if (DISPOSABLE_DOMAINS.has(domain)) return true;

  // Проверяем родительские домены: box.mailinator.com -> mailinator.com
  const parts = domain.split(".");
  for (let i = 1; i < parts.length - 1; i += 1) {
    if (DISPOSABLE_DOMAINS.has(parts.slice(i).join("."))) return true;
  }

  return false;
}

